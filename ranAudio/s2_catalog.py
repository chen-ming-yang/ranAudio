def jobs_summary(jobs: list[dict[str, Any]]) -> dict[str, Any]:
    from collections import Counter

    buckets = Counter(str(j.get("bucket")) for j in jobs)
    engines = Counter(str(j.get("engine")) for j in jobs)
    traps = sum(1 for j in jobs if j.get("trap"))
    return {
        "n": len(jobs),
        "buckets": dict(buckets),
        "engines": dict(engines),
        "asr_traps": traps,
        "clone_refs": len(clone_refs()),
    }
