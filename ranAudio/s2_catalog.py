def read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    if not path.is_file():
        return rows
    with path.open(encoding="utf-8") as f:
        for line in f:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def write_jsonl(path: Path, rows: Iterable[dict[str, Any]]) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            n += 1
    return n


def pick_weighted(rng: random.Random, items: list[tuple[Any, int]]) -> Any:
    total = sum(w for _, w in items)
    x = rng.randrange(total)
    acc = 0
    for item, w in items:
        acc += w
        if x < acc:
            return item
    return items[-1][0]


def pick_engine(rng: random.Random) -> str:
    return pick_weighted(rng, ENGINE_WEIGHTS)


def _uniq(seq: Iterable[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for s in seq:
        t = (s or "").strip()
        if not t or t in seen:
            continue
        seen.add(t)
        out.append(t)
    return out


def _fill(n: int, pool: list[str], rng: random.Random) -> list[str]:
    pool = _uniq(pool)
    if not pool:
        return []
    if len(pool) >= n:
        return pool[:n]
    extra = [rng.choice(pool) for _ in range(n - len(pool))]
    return pool + extra


@lru_cache(maxsize=1)
def car_unique_texts() -> list[str]:
    return _uniq(str(r.get("text") or "") for r in read_jsonl(CAR_TEXTS))


def clone_refs(limit: int = 16) -> list[dict[str, str]]:
    refs: list[dict[str, str]] = []
    for row in read_jsonl(CAR_TEXTS):
        sid = str(row.get("id") or "")
        if not (sid.endswith("_001") or sid.endswith("_006") or sid.endswith("_011")):
            continue
        wav = CAR_WAVS / f"{sid}.wav"
        text = str(row.get("text") or "").strip()
        if wav.is_file() and text:
            refs.append({"wav": str(wav), "text": text})
        if len(refs) >= limit:
            break
    return refs


def _attach_engine(row: dict[str, Any], rng: random.Random, refs: list[dict[str, str]]) -> dict[str, Any]:
    engine = pick_engine(rng)
    row["engine"] = engine
    if engine == "edge":
        row["voice"] = rng.choice(EDGE_VOICES)
    elif engine == "qwen_custom":
        row["voice"] = rng.choice(CUSTOM_SPEAKERS)
    elif engine == "qwen_design":
        row["instruct"] = rng.choice(DESIGN_INSTRUCTS)
        row["voice"] = "design"
    else:
        ref = rng.choice(refs) if refs else {"wav": "", "text": ""}
        row["voice"] = "clone"
        row["ref_wav"] = ref["wav"]
        row["ref_text"] = ref["text"]
    return row


