def chat_reply(text: str) -> str:
    t = (text or "").strip()
    for user, reply in chat_items_pool():
        if t == user:
            return reply
    return default_chat_reply(t)


def build_jobs(
    n_fc: int = N_FC_TTS,
    n_chat: int = N_CHAT_TTS,
    n_asr: int = N_ASR_TTS,
    seed: int = SEED,
) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    refs = clone_refs()
    jobs: list[dict[str, Any]] = []

    car_pool = car_unique_texts()
    general = fc_general_pool()
    rng.shuffle(general)
    n_car = min(1000, n_fc)
    n_gen = n_fc - n_car
    fc_texts = _fill(n_car, car_pool, rng) + _fill(n_gen, general, rng)
    rng.shuffle(fc_texts)
    for i, text in enumerate(fc_texts[:n_fc]):
        row = {
            "id": f"s2_fc_{i:04d}",
            "bucket": "fc",
            "kind": None,
            "venue": "base",
            "user": text,
            "source": "tts_new",
        }
        jobs.append(_attach_engine(row, rng, refs))

    chat_pool = list(chat_items_pool())
    rng.shuffle(chat_pool)
    chat_sel: list[tuple[str, str]] = []
    if len(chat_pool) >= n_chat:
        chat_sel = chat_pool[:n_chat]
    else:
        chat_sel = list(chat_pool)
        while len(chat_sel) < n_chat:
            chat_sel.append(rng.choice(chat_pool))
    for i, (user, reply) in enumerate(chat_sel[:n_chat]):
        row = {
            "id": f"s2_chat_{i:04d}",
            "bucket": "chat",
            "kind": "chat",
            "user": user,
            "reply": reply,
            "source": "tts_new",
        }
        jobs.append(_attach_engine(row, rng, refs))

    n_trap = int(round(n_asr * ASR_TRAP_RATIO))
    n_body = n_asr - n_trap
    bodies = _fill(n_body, asr_body_pool(), rng)
    traps = _fill(n_trap, asr_trap_bodies(), rng)
    asr_items = [(b, False) for b in bodies] + [(b, True) for b in traps]
    rng.shuffle(asr_items)
    for i, (body, trap) in enumerate(asr_items[:n_asr]):
        trigger = rng.choice(ASR_TRIGGERS)
        user = _join_asr(trigger, body, rng)
        row = {
            "id": f"s2_asr_{i:04d}",
            "bucket": "asr",
            "kind": "asr",
            "user": user,
            "body": body,
            "trap": trap,
            "source": "tts_new",
        }
        jobs.append(_attach_engine(row, rng, refs))
    return jobs


