def apply_lfr(inputs: torch.Tensor, lfr_m: int, lfr_n: int) -> torch.Tensor:
    t = inputs.shape[0]
    t_lfr = int(np.ceil(t / lfr_n))
    left = inputs[0].repeat((lfr_m - 1) // 2, 1)
    inputs = torch.vstack((left, inputs))
    t = t + (lfr_m - 1) // 2
    feat_dim = inputs.shape[-1]
    last_idx = (t - lfr_m) // lfr_n + 1
    num_padding = lfr_m - (t - last_idx * lfr_n)
    if num_padding > 0:
        num_padding = (2 * lfr_m - 2 * t + (t_lfr - 1 + last_idx) * lfr_n) / 2 * (t_lfr - last_idx)
        inputs = torch.vstack([inputs] + [inputs[-1:]] * int(num_padding))
    return inputs.as_strided((t_lfr, lfr_m * feat_dim), (lfr_n * feat_dim, 1)).clone()


def load_cmvn(path: Path) -> Optional[torch.Tensor]:
    if not path.is_file():
        return None
    means: list[str] = []
    scales: list[str] = []
    lines = path.read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines):
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "<AddShift>" and i + 1 < len(lines):
            nxt = lines[i + 1].split()
            if nxt and nxt[0] == "<LearnRateCoef>":
                means = nxt[3:-1]
        elif parts[0] == "<Rescale>" and i + 1 < len(lines):
            nxt = lines[i + 1].split()
            if nxt and nxt[0] == "<LearnRateCoef>":
                scales = nxt[3:-1]
    if not means or not scales:
        return None
    return torch.tensor([list(map(float, means)), list(map(float, scales))], dtype=torch.float32)


def wav_to_lfr(
    wav: np.ndarray,
    *,
    cmvn: Optional[torch.Tensor] = None,
    fs: int = 16000,
) -> torch.Tensor:
    """16k waveform -> [T, 560] LFR fbank (SenseVoice frontend)."""
    wav = np.asarray(wav, dtype=np.float32).reshape(-1)
    waveform = torch.from_numpy(wav).unsqueeze(0) * (1 << 15)
    if waveform.shape[-1] < int(0.025 * fs):
        waveform = torch.nn.functional.pad(waveform, (0, int(0.025 * fs) - waveform.shape[-1]))
    mat = kaldi.fbank(
        waveform,
        num_mel_bins=80,
        frame_length=25.0,
        frame_shift=10.0,
        dither=0.0,
        energy_floor=0.0,
        window_type="hamming",
        sample_frequency=fs,
        snip_edges=True,
    )
    mat = apply_lfr(mat, 7, 6)
    if cmvn is not None:
        dim = mat.shape[-1]
        shift_scale = cmvn.to(device=mat.device, dtype=mat.dtype)
        mat = (mat + shift_scale[0:1, :dim]) * shift_scale[1:2, :dim]
    return mat


def resolve_sensevoice_dir(path: str | Path, download: bool = True) -> Path:
    p = Path(path)
    candidates = [
        p,
        p.parent / "iic" / "SenseVoiceSmall",
        p.parent / "SenseVoiceSmall",
    ]
    for c in candidates:
        if (c / "model.pt").is_file() or (c / "model.safetensors").is_file():
            return c
    if not download:
        raise FileNotFoundError(f"SenseVoice-Small not found at {p}")
    p.parent.mkdir(parents=True, exist_ok=True)
    from modelscope.hub.snapshot_download import snapshot_download

    cached = snapshot_download("iic/SenseVoiceSmall", cache_dir=str(p.parent))
    cached_p = Path(cached)
    if cached_p.resolve() != p.resolve() and not p.exists():
        try:
            p.symlink_to(cached_p, target_is_directory=True)
        except OSError:
            return cached_p
    return p if (p / "model.pt").is_file() else cached_p


class SenseVoiceAPM(nn.Module):
    """Encoder slot: SenseVoice-Small encoder + lang/style queries. Out dim=512."""

    def __init__(self, model_dir: str | Path, device: torch.device, dtype: torch.dtype):
        super().__init__()
        model_dir = resolve_sensevoice_dir(model_dir)
        self.model_dir = model_dir
        self.encoder = SenseVoiceEncoderSmall(input_size=INPUT_SIZE, **ENCODER_CONF)
        self.embed = nn.Embedding(7 + len(LID) + len(TEXTNORM), INPUT_SIZE)
        self._load_weights(model_dir)
        cmvn = load_cmvn(model_dir / "am.mvn")
        if cmvn is not None:
            self.register_buffer("cmvn", cmvn, persistent=False)
        else:
            self.cmvn = None
        # SANM FSMN is Conv1d; bf16 kernels are missing on CPU. FunASR runs fp32.
        _ = dtype
        self.to(device=device, dtype=torch.float32)
        self.out_dim = int(self.encoder.output_size())

    def _load_weights(self, model_dir: Path) -> None:
        ckpt = model_dir / "model.pt"
        if not ckpt.is_file():
            raise FileNotFoundError(f"missing {ckpt}")
        raw = torch.load(str(ckpt), map_location="cpu", weights_only=False)
        if isinstance(raw, dict) and "state_dict" in raw:
            raw = raw["state_dict"]
        enc = {k[len("encoder.") :]: v for k, v in raw.items() if k.startswith("encoder.")}
        emb = {k[len("embed.") :]: v for k, v in raw.items() if k.startswith("embed.")}
        missing, unexpected = self.encoder.load_state_dict(enc, strict=False)
        if missing:
            print(f"sensevoice encoder missing={missing[:6]} n={len(missing)}", flush=True)
        if unexpected:
            print(f"sensevoice encoder unexpected={unexpected[:6]}", flush=True)
        if emb:
            self.embed.load_state_dict(emb, strict=True)

    def encode_wav(self, wav: np.ndarray, language: str = "zh") -> torch.Tensor:
        """Return acoustic frames [T, 512], query tokens stripped."""
        return self.encode_wavs([wav], language=language)[0]

    def encode_wavs(self, wavs: list[np.ndarray], language: str = "zh") -> list[torch.Tensor]:
        """Batched encode. Returns one [T_i, 512] per wav, query tokens stripped."""
        feat_list = [wav_to_lfr(w, cmvn=self.cmvn) for w in wavs]
        device = self.embed.weight.device
        dtype = self.embed.weight.dtype
        lengths = torch.tensor([int(f.shape[0]) for f in feat_list], device=device, dtype=torch.long)
        max_t = int(lengths.max().item()) if len(feat_list) else 0
        padded = torch.zeros(len(feat_list), max_t, INPUT_SIZE, device=device, dtype=dtype)
        for i, feat in enumerate(feat_list):
            padded[i, : feat.shape[0]] = feat.to(device=device, dtype=dtype)
        b = padded.shape[0]
        lang = self.embed(
            torch.tensor([[LID.get(language, LID["auto"])]], device=device)
        ).expand(b, -1, -1)
        style = self.embed(torch.tensor([[TEXTNORM["woitn"]]], device=device)).expand(b, -1, -1)
        event_emo = self.embed(torch.tensor([[1, 2]], device=device)).expand(b, -1, -1)
        speech = torch.cat((lang, event_emo, style, padded), dim=1)
        olens = lengths + QUERY_FRAMES
        hidden, _ = self.encoder(speech, olens)
        out: list[torch.Tensor] = []
        for i, t in enumerate(lengths.tolist()):
            out.append(hidden[i, QUERY_FRAMES : QUERY_FRAMES + int(t), :])
        return out


